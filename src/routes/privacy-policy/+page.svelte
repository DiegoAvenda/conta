	<div class="space-y-8 text-base leading-8">
		<section>
			<p>
				En <strong>Contaco</strong> (en adelante, “Contaco”, “la Plataforma” o “nosotros”) respetamos
				la privacidad de nuestros usuarios y nos comprometemos a proteger la información personal que
				tratamos a través de nuestros servicios.
			</p>

			<p class="mt-4">
				Esta Política de Privacidad explica qué información podemos recopilar, para qué la
				utilizamos, cómo la protegemos y qué opciones tienen los usuarios respecto de sus datos.
			</p>
		</section>

		<section>
			<h2 class="text-2xl font-semibold text-slate-900">1. Información que recopilamos</h2>

			<p class="mt-3">
				Dependiendo de las funcionalidades utilizadas, Contaco puede recopilar y procesar las
				siguientes categorías de información:
			</p>

			<ul class="mt-3 list-disc space-y-3 pl-6">
				<li>
					<strong>Datos de cuenta:</strong> nombre, dirección de correo electrónico, número de teléfono
					y otros datos necesarios para crear y administrar una cuenta.
				</li>

				<li>
					<strong>Datos del negocio:</strong> nombre comercial, información de contacto, dirección, información
					relacionada con el establecimiento y otros datos que el restaurante proporcione para utilizar
					nuestros servicios.
				</li>

				<li>
					<strong>Información de pedidos y ventas:</strong> productos, cantidades, precios, órdenes, información
					relacionada con transacciones y otros datos necesarios para proporcionar las funciones de gestión
					del restaurante.
				</li>

				<li>
					<strong>Datos técnicos:</strong> dirección IP, tipo de navegador, dispositivo, registros técnicos
					y otra información necesaria para mantener la seguridad, estabilidad y funcionamiento de la
					Plataforma.
				</li>
			</ul>
		</section>

		<section>
			<h2 class="text-2xl font-semibold text-slate-900">2. Finalidades del tratamiento</h2>

			<p class="mt-3">Utilizamos la información recopilada para las siguientes finalidades:</p>

			<ol class="mt-3 list-decimal space-y-3 pl-6">
				<li>
					<strong>Prestar nuestros servicios:</strong> proporcionar las herramientas de gestión de pedidos,
					ventas, productos, inventario y demás funcionalidades contratadas.
				</li>

				<li>
					<strong>Gestionar integraciones:</strong> conectar y mantener las integraciones que el restaurante
					solicite.
				</li>

				<li>
					<strong>Procesar pedidos:</strong> recibir, organizar y registrar información necesaria para
					gestionar pedidos y ventas.
				</li>

				<li>
					<strong>Seguridad:</strong> detectar, prevenir e investigar accesos no autorizados, fraude,
					abuso y otras actividades que puedan afectar la seguridad de la Plataforma.
				</li>

				<li>
					<strong>Soporte:</strong> responder solicitudes, resolver problemas técnicos y comunicarnos
					con los usuarios respecto del funcionamiento del servicio.
				</li>

				<li>
					<strong>Mejora del servicio:</strong> analizar información técnica y estadística de forma agregada
					cuando sea posible para mejorar el rendimiento, estabilidad y funcionalidad de Contaco.
				</li>

				<li>
					<strong>Cumplimiento legal:</strong> cumplir obligaciones legales, fiscales, administrativas
					o requerimientos válidos de autoridades competentes.
				</li>
			</ol>
		</section>

		<section>
			<h2 class="text-2xl font-semibold text-slate-900">
				3. Integraciones y proveedores de servicios
			</h2>

			<p class="mt-3">
				Contaco puede utilizar proveedores tecnológicos y servicios de terceros necesarios para el
				funcionamiento de la Plataforma, tales como servicios de alojamiento, bases de datos,
				almacenamiento, procesamiento de pagos, autenticación, comunicaciones y otros servicios de
				infraestructura.
			</p>

			<p class="mt-4">
				Cuando utilizamos proveedores externos, procuramos limitar el acceso a la información a lo
				necesario para proporcionar sus servicios y aplicamos medidas razonables para proteger los
				datos procesados.
			</p>
		</section>

		<section>
			<h2 class="text-2xl font-semibold text-slate-900">4. Compartición de información</h2>

			<p class="mt-3">Contaco no vende ni alquila información personal a terceros.</p>

			<p class="mt-4">
				Podemos compartir o permitir el acceso a información cuando sea necesario para:
			</p>

			<ul class="mt-3 list-disc space-y-2 pl-6">
				<li>Proporcionar los servicios solicitados por el usuario.</li>
				<li>Operar nuestra infraestructura tecnológica.</li>
				<li>Procesar pagos u otras operaciones solicitadas.</li>
				<li>Mantener y proteger la seguridad de la Plataforma.</li>
				<li>Cumplir obligaciones legales o requerimientos válidos de autoridades.</li>
			</ul>
		</section>

		<section>
			<h2 class="text-2xl font-semibold text-slate-900">
				5. Conservación y eliminación de información
			</h2>

			<p class="mt-3">
				Conservamos la información durante el tiempo necesario para proporcionar nuestros servicios,
				mantener registros relacionados con las operaciones realizadas, resolver controversias y
				cumplir obligaciones legales, fiscales o administrativas aplicables.
			</p>

			<p class="mt-4">
				Cuando un usuario solicita la eliminación de su cuenta o cuando finaliza una relación de
				servicio, podremos eliminar o anonimizar la información cuando corresponda, salvo aquella
				que debamos conservar por obligaciones legales, seguridad, prevención de fraude o legítimas
				necesidades operativas.
			</p>
		</section>

		<section>
			<h2 class="text-2xl font-semibold text-slate-900">6. Seguridad de la información</h2>

			<p class="mt-3">
				Implementamos medidas técnicas y administrativas razonables destinadas a proteger la
				información contra acceso no autorizado, pérdida, alteración, divulgación o destrucción.
			</p>

			<p class="mt-4">
				Entre estas medidas pueden incluirse comunicaciones cifradas mediante HTTPS/TLS, controles
				de acceso, autenticación y medidas de protección de nuestra infraestructura tecnológica.
			</p>

			<p class="mt-4">
				Ningún sistema conectado a Internet puede garantizar seguridad absoluta. Por ello, revisamos
				y mejoramos continuamente nuestras medidas de seguridad conforme evoluciona la Plataforma.
			</p>
		</section>

		<section>
			<h2 class="text-2xl font-semibold text-slate-900">7. Derechos de los usuarios</h2>

			<p class="mt-3">
				Los usuarios pueden solicitar información sobre los datos personales que Contaco mantiene
				sobre ellos y, cuando corresponda, solicitar su corrección o eliminación.
			</p>

			<p class="mt-4">
				Las solicitudes relacionadas con información personal pueden realizarse utilizando los datos
				de contacto indicados al final de esta Política.
			</p>

			<p class="mt-4">
				Los restaurantes también pueden gestionar o desconectar las integraciones de terceros desde
				las herramientas correspondientes proporcionadas por dichos servicios.
			</p>
		</section>

		<section>
			<h2 class="text-2xl font-semibold text-slate-900">
				8. Privacidad de los clientes de los restaurantes
			</h2>

			<p class="mt-3">
				Contaco proporciona herramientas para que los restaurantes gestionen pedidos y operaciones
				de su negocio. Cuando un comensal interactúa directamente con un restaurante, determinados
				datos pueden ser procesados por Contaco en nombre del restaurante para proporcionar la
				funcionalidad solicitada.
			</p>

			<p class="mt-4">
				En estos casos, el restaurante es responsable de proporcionar a sus clientes la información
				y avisos de privacidad que resulten aplicables a su propia actividad y de cumplir las
				obligaciones legales correspondientes.
			</p>
		</section>

